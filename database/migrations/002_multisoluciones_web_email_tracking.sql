    UPDATE public.contacts c SET locale = COALESCE((
      SELECT r.locale FROM public.requests r WHERE r.contact_id = c.id
        AND r.locale IN ('en', 'es', 'ko', 'pt') ORDER BY r.id DESC LIMIT 1
